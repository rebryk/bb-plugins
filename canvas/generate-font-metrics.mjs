import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

// Reproduce with `node generate-font-metrics.mjs` after npm ci.
const require = createRequire(import.meta.url);
const path = require.resolve("dejavu-fonts-ttf/ttf/DejaVuSans.ttf");
const font = await readFile(path);
const u16 = (offset) => font.readUInt16BE(offset);
const u32 = (offset) => font.readUInt32BE(offset);
const tables = new Map();
for (let offset = 12; offset < 12 + u16(4) * 16; offset += 16)
  tables.set(font.toString("ascii", offset, offset + 4), u32(offset + 8));
const cmap = tables.get("cmap");
let unicode;
for (let offset = cmap + 4; offset < cmap + 4 + u16(cmap + 2) * 8; offset += 8) {
  const table = cmap + u32(offset + 4);
  if (u16(table) === 12) unicode = table;
}
if (unicode === undefined) throw new Error("Expected a Unicode format-12 cmap.");
const units = u16(tables.get("head") + 18);
const metricCount = u16(tables.get("hhea") + 34);
const advance = (glyph) => u16(tables.get("hmtx") + Math.min(glyph, metricCount - 1) * 4);
const entries = [];
for (let offset = unicode + 16; offset < unicode + 16 + u32(unicode + 12) * 12; offset += 12) {
  const start = u32(offset), end = u32(offset + 4), firstGlyph = u32(offset + 8);
  for (let code = start; code <= end; code++)
    entries.push(code, advance(firstGlyph + code - start));
}
const lines = [];
for (let offset = 0; offset < entries.length; offset += 16)
  lines.push(`  ${entries.slice(offset, offset + 16).join(", ")},`);
const output = `// Generated by generate-font-metrics.mjs; do not edit by hand.
// Source: dejavu-fonts-ttf/ttf/DejaVuSans.ttf, DejaVu Sans 2.37.
// SHA-256: ${createHash("sha256").update(font).digest("hex")}
// Copyright Bitstream, Inc. and Tavmjong Bah; DejaVu changes are public domain.
// Redistribution terms: assets/DejaVu-Font-LICENSE.txt.
export const FONT_UNITS = ${units};
export const MISSING_ADVANCE = ${advance(0)};
const pairs: readonly number[] = [
${lines.join("\n")}
];
export const FONT_ADVANCES: ReadonlyMap<number, number> = new Map(
  Array.from({ length: pairs.length / 2 }, (_, i) => [pairs[i * 2]!, pairs[i * 2 + 1]!]),
);
`;
await writeFile(new URL("./font-metrics.ts", import.meta.url), output);
await writeFile(
  new URL("./assets/DejaVu-Font-LICENSE.txt", import.meta.url),
  (await readFile(require.resolve("dejavu-fonts-ttf/LICENSE"), "utf8")).replace(/[ \t]+$/gm, ""),
);
